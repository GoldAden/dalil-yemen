-- 1) الجدول -----------------------------------------------------------

create table if not exists public.places (
    id            bigint generated by default as identity primary key,
    name          text        not null,
    category_id   text,
    city_id       text,
    phone         text,
    address       text,
    opening_hours text,
    notes         text,
    latitude      double precision,
    longitude     double precision,
    kind_key      text,
    kind_value    text,
    -- المراجعة: كل مساهمة تبدأ بحالة pending ولا تظهر قبل اعتمادها.
    status        text        not null default 'pending',
    created_at    timestamptz not null default now(),
    updated_at    timestamptz not null default now(),

    -- أقل شرط مقبول: اسم غير فارغ بعد إزالة المسافات.
    constraint places_name_not_blank  check (length(btrim(name)) > 0),
    -- حالة واحدة فقط من ثلاث، حتى لا يدخل جدولنا ما لا نفهمه.
    constraint places_status_allowed  check (status in ('pending', 'approved', 'rejected')),
    -- إن وُجدت إحداثيات فلتكن داخل حدود اليمن التقريبية.
    constraint places_coordinates_in_yemen check (
        latitude  is null
        or longitude is null
        or (   latitude  between 12.0 and 19.2
           and longitude between 42.0 and 54.8)
    )
);

-- 2) الفهارس ---------------------------------------------------------
--    القراءة العامة تمرّ دائماً على status = 'approved' مرتّبة بالأحدث،
--    والبحث المحلي في التطبيق يعتمد على التصنيف والمدينة.

create index if not exists places_status_updated_idx
    on public.places (status, updated_at desc);

create index if not exists places_category_idx
    on public.places (category_id);

create index if not exists places_city_idx
    on public.places (city_id);

-- 3) تحديث updated_at تلقائياً ---------------------------------------

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

drop trigger if exists places_touch_updated_at on public.places;

create trigger places_touch_updated_at
    before update on public.places
    for each row
    execute function public.touch_updated_at();

-- 4) حماية الصفوف (Row Level Security) -------------------------------
--
--  القاعدة: القراءة للجميع لكن للسجلّات المعتمدة فقط، والكتابة للجميع
--  (إرسال مساهمة) لكن بحالة 'pending' حصراً — فلا يستطيع أحد أن يعتمد
--  مساهمته بنفسه، ولا أن يُعدّل ما أرسله غيره.

-- الجدول يُستخدم عبر واجهة REST؛ مفتاح anon العام هو ما يملكه التطبيق.
grant select, insert on public.places to anon, authenticated;
-- الاعتماد والتعديل يبقى لصاحب المشروع عبر مفتاح الخدمة (service_role).
grant update, delete on public.places to service_role;
-- تسلسل المعرّفات: الإدراج يحتاج صلاحية استخدام التسلسل فقط.
grant usage, select on sequence public.places_id_seq to anon, authenticated;

alter table public.places enable row level security;

drop policy if exists places_public_read_approved on public.places;
create policy places_public_read_approved
    on public.places
    for select
    to anon, authenticated
    using (status = 'approved');

drop policy if exists places_public_insert_pending on public.places;
create policy places_public_insert_pending
    on public.places
    for insert
    to anon, authenticated
    with check (
        status = 'pending'
        and length(btrim(name)) > 0
        and (
            latitude  is null
            or longitude is null
            or (   latitude  between 12.0 and 19.2
               and longitude between 42.0 and 54.8)
        )
    );

-- لا سياسة تحديث ولا حذف لغير service_role، وهذا مقصود.

-- 5) فائدة إضافية: محرّك قراءة عام محدّد ------------------------------
--
--  التطبيق يقرأ /rest/v1/places?status=eq.approved&order=updated_at.desc
--  ويمكنه أيضاً استخدام هذا المنظور الجاهز إن أراد تبسيط الطلبات.

create or replace view public.approved_places as
    select id, name, category_id, city_id, phone, address,
           opening_hours, notes, latitude, longitude,
           kind_key, kind_value, updated_at
    from public.places
    where status = 'approved';

grant select on public.approved_places to anon, authenticated;

